import { execSync } from 'node:child_process'

const staged = execSync('git diff --cached --name-only --diff-filter=ACMR', { encoding: 'utf8' })
  .split('\n')
  .filter(Boolean)

const envFiles = staged.filter(file => /(^|\/)\.env(\..+)?$/.test(file) && !file.endsWith('.env.example'))
const distFiles = staged.filter(file => file.startsWith('dist/'))

if (envFiles.length === 0 && distFiles.length === 0) {
  process.exit(0)
}

console.error('\nCommit blocked: forbidden files are staged.\n')

if (envFiles.length > 0) {
  console.error('Environment files must never be committed (only .env.example is allowed):')
  envFiles.forEach(file => console.error(`  - ${file}`))
  console.error('Fix: git restore --staged <file>\n')
}

if (distFiles.length > 0) {
  console.error('Build output dist/ is generated by CI and must not be committed:')
  console.error(`  - ${distFiles.length} file(s) under dist/`)
  console.error('Fix: git restore --staged dist\n')
}

process.exit(1)
